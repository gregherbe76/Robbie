/**
 * BenchmarkReportEngine — turns scenario results into JSON, markdown,
 * and console-readable summaries. No ANSI codes here (the CLI applies
 * them); the markdown / console output must be terminal-safe.
 */

import type { BenchmarkReport, ScenarioResult } from "./types.js";

export function renderMarkdownReport(report: BenchmarkReport): string {
  const lines: string[] = [];
  lines.push(`# Cognitive Benchmark Report`);
  lines.push("");
  lines.push(`Generated at: \`${report.generatedAt}\``);
  lines.push(`Generated by: \`${report.generatedBy}\``);
  lines.push("");
  lines.push(`## Summary`);
  lines.push("");
  lines.push(`- Scenarios: **${report.summary.totalScenarios}**`);
  lines.push(`- Passed: **${report.summary.passed}**`);
  lines.push(`- Failed: **${report.summary.failed}**`);
  lines.push(`- Determinism: ${report.summary.determinismOk ? "OK" : "FAILED"}`);
  lines.push(`- Provenance: ${report.summary.provenanceOk ? "OK" : "FAILED"}`);
  lines.push(`- Calibration: ${report.summary.calibrationOk ? "OK" : "FAILED"}`);
  lines.push(`- Snapshot: ${report.summary.snapshotOk ? "OK" : "DRIFT"}`);
  lines.push(`- Mutation guards: ${report.summary.mutationGuardsOk ? "OK" : "FAILED"}`);
  lines.push("");
  lines.push(`## Scenario Results`);
  lines.push("");
  lines.push(`| Scenario | Status | Determinism | Cognition | Provenance | Failures |`);
  lines.push(`| --- | --- | --- | --- | --- | --- |`);
  report.scenarios.forEach((s) => {
    lines.push(
      `| ${s.scenarioId} | ${s.passed ? "PASS" : "FAIL"} | ${s.determinism.passed ? "ok" : "drift"} | ${s.cognitionIntegrity.passed ? "ok" : "fail"} | ${s.provenance.ok ? "ok" : "fail"} | ${s.failures.length} |`,
    );
  });
  lines.push("");
  lines.push(`## Calibration Smoke`);
  lines.push("");
  lines.push(
    `- ECE: **${report.calibration.ece}** (${report.calibration.overconfidenceRisk} risk, ${report.calibration.predictionsEvaluated} predictions)`,
  );
  lines.push(`- ${report.calibration.detail}`);
  if (report.calibration.reasons.length > 0) {
    report.calibration.reasons.forEach((r) => lines.push(`  - ${r}`));
  }
  lines.push("");
  lines.push(`## Snapshot Drift`);
  lines.push("");
  if (report.snapshot.ok) {
    lines.push("No drift.");
  } else {
    report.snapshot.drift.forEach((d) =>
      lines.push(`- \`${d.scenarioId}\` (${d.kind}): ${d.detail}`),
    );
  }
  lines.push("");
  lines.push(`## Mutation Guards`);
  lines.push("");
  report.mutationGuards.forEach((g) =>
    lines.push(`- ${g.passed ? "OK" : "WEAK"} \`${g.guardId}\` — ${g.description} (${g.detail})`),
  );
  lines.push("");
  lines.push(`## Recommended Fixes`);
  lines.push("");
  if (report.recommendations.length === 0) {
    lines.push("None.");
  } else {
    report.recommendations.forEach((r) => lines.push(`- ${r}`));
  }
  lines.push("");
  return lines.join("\n");
}

export function renderConsoleSummary(report: BenchmarkReport): string {
  const lines: string[] = [];
  lines.push(`Cognitive benchmark — ${report.summary.passed}/${report.summary.totalScenarios} passed`);
  lines.push(
    `  determinism=${report.summary.determinismOk ? "ok" : "fail"}  provenance=${report.summary.provenanceOk ? "ok" : "fail"}  calibration=${report.summary.calibrationOk ? "ok" : "fail"}  snapshot=${report.summary.snapshotOk ? "ok" : "drift"}  guards=${report.summary.mutationGuardsOk ? "ok" : "fail"}`,
  );
  report.scenarios.forEach((s) => {
    lines.push(
      `  ${s.passed ? "PASS" : "FAIL"} ${s.scenarioId}  (failures: ${s.failures.length})`,
    );
    if (!s.passed) {
      s.failures.forEach((f) => {
        const path = f.expectation.path ?? "(no path)";
        lines.push(`      - [${f.expectation.type}] ${path}: ${f.detail}`);
      });
      s.cognitionIntegrity.findings
        .filter((f) => !f.ok)
        .forEach((f) => lines.push(`      ! integrity:${f.rule} — ${f.detail}`));
    }
  });
  if (!report.calibration.passed) {
    lines.push(`  ! calibration: ${report.calibration.detail}`);
    report.calibration.reasons.forEach((r) => lines.push(`      - ${r}`));
  }
  if (!report.snapshot.ok) {
    lines.push(`  ! snapshot drift:`);
    report.snapshot.drift.forEach((d) =>
      lines.push(`      - ${d.scenarioId} (${d.kind}): ${d.detail}`),
    );
  }
  report.mutationGuards
    .filter((g) => !g.passed)
    .forEach((g) => lines.push(`  ! guard:${g.guardId} — ${g.detail}`));
  return lines.join("\n");
}

export function deriveRecommendations(scenarios: ScenarioResult[]): string[] {
  const out: string[] = [];
  scenarios.forEach((s) => {
    if (!s.passed) {
      out.push(
        `Investigate ${s.scenarioId}: ${s.failures.length} expectation(s) failed, ${s.cognitionIntegrity.findings.filter((f) => !f.ok).length} integrity rule(s) broken.`,
      );
    }
    if (!s.determinism.passed) {
      out.push(
        `Determinism leak in ${s.scenarioId}: ${s.determinism.drift.slice(0, 2).join(" | ")}`,
      );
    }
    if (!s.provenance.ok) {
      out.push(
        `Provenance gap in ${s.scenarioId}: ${s.provenance.findings.filter((f) => !f.ok).map((f) => f.path).slice(0, 3).join(", ")}`,
      );
    }
  });
  return out;
}
